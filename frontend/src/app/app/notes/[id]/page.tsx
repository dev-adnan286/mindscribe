"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useParams, useRouter } from "next/navigation";
import { useCallback, useEffect, useRef, useState } from "react";

import { Badge } from "@/components/Badge";
import { Button } from "@/components/Button";
import { EmptyState } from "@/components/EmptyState";
import { Modal } from "@/components/Modal";
import { NoteEditor } from "@/components/NoteEditor";
import { LineSkeleton } from "@/components/Skeleton";
import { TagInput } from "@/components/TagInput";
import { useToast } from "@/components/Toast";
import { VersionHistoryDrawer } from "@/components/VersionHistoryDrawer";
import { ApiError, aiApi, notebooksApi, notesApi, tagsApi, type Note, type NoteUpdateInput } from "@/lib/api";
import { formatDate } from "@/lib/utils";

const AUTOSAVE_MS = 1200;

type SaveState = "idle" | "dirty" | "saving" | "saved" | "error";

export default function NoteDetailPage() {
  const { id } = useParams<{ id: string }>();
  const router = useRouter();
  const queryClient = useQueryClient();
  const toast = useToast();

  const note = useQuery({ queryKey: ["note", id], queryFn: () => notesApi.get(id) });
  const notebooks = useQuery({ queryKey: ["notebooks"], queryFn: notebooksApi.list });
  const existingTags = useQuery({ queryKey: ["tags"], queryFn: tagsApi.list });

  const [title, setTitle] = useState("");
  const [content, setContent] = useState("");
  const [tags, setTags] = useState<string[]>([]);
  const [notebookId, setNotebookId] = useState("");
  const [summary, setSummary] = useState<string | null>(null);
  const [suggested, setSuggested] = useState<string[]>([]);
  const [saveState, setSaveState] = useState<SaveState>("idle");
  const [historyOpen, setHistoryOpen] = useState(false);
  const [confirmDelete, setConfirmDelete] = useState(false);
  const loadedVersion = useRef<number | null>(null);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const pendingRef = useRef<NoteUpdateInput>({});

  // Hydrate local editor state whenever a new version of the note arrives from the server.
  useEffect(() => {
    if (!note.data) return;
    if (loadedVersion.current === note.data.version && saveState !== "idle") return;
    loadedVersion.current = note.data.version;
    setTitle(note.data.title);
    setContent(note.data.content);
    setTags(note.data.tags);
    setNotebookId(note.data.notebook_id ?? "");
    setSummary(note.data.summary);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [note.data]);

  const applyServerNote = useCallback(
    (updated: Note) => {
      loadedVersion.current = updated.version;
      queryClient.setQueryData(["note", id], updated);
      void queryClient.invalidateQueries({ queryKey: ["notes"] });
      void queryClient.invalidateQueries({ queryKey: ["tags"] });
      void queryClient.invalidateQueries({ queryKey: ["note-versions", id] });
    },
    [id, queryClient],
  );

  const save = useMutation({
    mutationFn: (data: NoteUpdateInput) => notesApi.update(id, data),
    onMutate: () => setSaveState("saving"),
    onSuccess: (updated) => {
      applyServerNote(updated);
      setSummary(updated.summary);
      setSaveState("saved");
    },
    onError: (error) => {
      setSaveState("error");
      toast.error("Autosave failed", error instanceof ApiError ? error.message : undefined);
    },
  });

  const scheduleSave = useCallback(
    (changes: NoteUpdateInput) => {
      pendingRef.current = { ...pendingRef.current, ...changes };
      setSaveState("dirty");
      if (timer.current) clearTimeout(timer.current);
      timer.current = setTimeout(() => {
        const payload = pendingRef.current;
        pendingRef.current = {};
        if (payload.title !== undefined && !payload.title.trim()) {
          setSaveState("error");
          toast.error("Title cannot be empty");
          return;
        }
        save.mutate(payload);
      }, AUTOSAVE_MS);
    },
    [save, toast],
  );

  useEffect(() => () => {
    if (timer.current) clearTimeout(timer.current);
  }, []);

  const summarize = useMutation({
    mutationFn: () => aiApi.summarize({ note_id: id, apply: true }),
    onSuccess: (result) => {
      setSummary(result.summary);
      void queryClient.invalidateQueries({ queryKey: ["note", id] });
      void queryClient.invalidateQueries({ queryKey: ["notes"] });
      toast.success("Summary added", `Generated by the ${result.provider} provider`);
    },
    onError: (error) => toast.error("Could not summarise", error instanceof ApiError ? error.message : undefined),
  });

  const suggest = useMutation({
    mutationFn: () => aiApi.suggestTags({ note_id: id, max_tags: 6 }),
    onSuccess: (result) => {
      setSuggested(result.tags.filter((tag) => !tags.includes(tag)));
      if (result.tags.length === 0) toast.info("No new tag suggestions");
    },
    onError: (error) => toast.error("Could not suggest tags", error instanceof ApiError ? error.message : undefined),
  });

  const restore = useMutation({
    mutationFn: (version: number) => notesApi.restore(id, version),
    onSuccess: (updated) => {
      applyServerNote(updated);
      setTitle(updated.title);
      setContent(updated.content);
      setTags(updated.tags);
      setSummary(updated.summary);
      setSaveState("saved");
      setHistoryOpen(false);
      toast.success(`Restored as version ${updated.version}`);
    },
    onError: (error) => toast.error("Restore failed", error instanceof ApiError ? error.message : undefined),
  });

  const remove = useMutation({
    mutationFn: () => notesApi.remove(id),
    onSuccess: () => {
      void queryClient.invalidateQueries({ queryKey: ["notes"] });
      void queryClient.invalidateQueries({ queryKey: ["tags"] });
      void queryClient.invalidateQueries({ queryKey: ["stats"] });
      toast.success("Note deleted");
      router.replace("/app/notes");
    },
    onError: (error) => toast.error("Delete failed", error instanceof ApiError ? error.message : undefined),
  });

  if (note.isLoading) return <LineSkeleton lines={8} />;
  if (note.isError || !note.data) {
    return (
      <EmptyState
        title="Note not found"
        description="It may have been deleted, or you may not have access to it."
        icon="!"
        action={
          <Button variant="secondary" onClick={() => router.push("/app/notes")}>
            Back to notes
          </Button>
        }
      />
    );
  }

  const saveLabel: Record<SaveState, string> = {
    idle: "",
    dirty: "Unsaved changes",
    saving: "Saving...",
    saved: "All changes saved",
    error: "Save failed",
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-3 text-sm text-slate-500">
          <Button variant="ghost" size="sm" onClick={() => router.push("/app/notes")}>
            ← Notes
          </Button>
          <span aria-live="polite" className={saveState === "error" ? "text-red-600" : undefined}>
            {saveLabel[saveState]}
          </span>
          <Badge>v{note.data.version}</Badge>
        </div>
        <div className="flex flex-wrap gap-2" role="toolbar" aria-label="AI tools">
          <Button variant="secondary" size="sm" onClick={() => summarize.mutate()} loading={summarize.isPending}>
            Summarize
          </Button>
          <Button variant="secondary" size="sm" onClick={() => suggest.mutate()} loading={suggest.isPending}>
            Suggest tags
          </Button>
          <Button variant="secondary" size="sm" onClick={() => setHistoryOpen(true)}>
            History
          </Button>
          <Button variant="danger" size="sm" onClick={() => setConfirmDelete(true)}>
            Delete
          </Button>
        </div>
      </div>

      {summary && (
        <div className="rounded-xl border border-brand-200 bg-brand-50 p-4 text-sm dark:border-brand-900 dark:bg-brand-950/40">
          <div className="mb-1 flex items-center justify-between">
            <span className="text-xs font-semibold uppercase tracking-wide text-brand-700 dark:text-brand-200">AI summary</span>
            <button
              type="button"
              className="text-xs text-brand-600 hover:underline dark:text-brand-300"
              onClick={() => {
                setSummary(null);
                save.mutate({ summary: null });
              }}
            >
              Remove
            </button>
          </div>
          <p className="text-slate-800 dark:text-slate-200">{summary}</p>
        </div>
      )}

      <NoteEditor
        title={title}
        content={content}
        onTitleChange={(value) => {
          setTitle(value);
          scheduleSave({ title: value });
        }}
        onContentChange={(value) => {
          setContent(value);
          scheduleSave({ content: value });
        }}
      />

      <div className="grid gap-4 md:grid-cols-[1fr_240px]">
        <TagInput
          value={tags}
          onChange={(next) => {
            setTags(next);
            setSuggested((current) => current.filter((tag) => !next.includes(tag)));
            scheduleSave({ tags: next });
          }}
          suggestions={[...suggested, ...(existingTags.data?.map((t) => t.name) ?? [])]}
        />
        <div>
          <label htmlFor="notebook" className="block text-sm font-medium text-slate-700 dark:text-slate-300">
            Notebook
          </label>
          <select
            id="notebook"
            value={notebookId}
            onChange={(event) => {
              const value = event.target.value;
              setNotebookId(value);
              scheduleSave(value ? { notebook_id: value } : { clear_notebook: true });
            }}
            className="input mt-1"
          >
            <option value="">No notebook</option>
            {notebooks.data?.map((nb) => (
              <option key={nb.id} value={nb.id}>
                {nb.name}
              </option>
            ))}
          </select>
          <p className="mt-3 text-xs text-slate-500">
            Created {formatDate(note.data.created_at)} · Updated {formatDate(note.data.updated_at, { hour: "2-digit", minute: "2-digit" })}
          </p>
        </div>
      </div>

      <VersionHistoryDrawer
        noteId={id}
        currentVersion={note.data.version}
        open={historyOpen}
        onClose={() => setHistoryOpen(false)}
        onRestore={(version) => restore.mutate(version)}
        restoring={restore.isPending}
      />

      <Modal
        open={confirmDelete}
        onClose={() => setConfirmDelete(false)}
        title="Delete this note?"
        description="The note will be hidden from your library. Its version history is retained on the server."
        size="sm"
        footer={
          <>
            <Button variant="secondary" onClick={() => setConfirmDelete(false)}>
              Cancel
            </Button>
            <Button variant="danger" onClick={() => remove.mutate()} loading={remove.isPending}>
              Delete
            </Button>
          </>
        }
      >
        <p className="text-sm text-slate-600 dark:text-slate-400">&quot;{note.data.title}&quot;</p>
      </Modal>
    </div>
  );
}
